TARGET_CELLS = frozenset(
    {("aim990", locale) for locale in AIM_COPY}
    | {("lumibopomofo", locale) for locale in LOCALES}
    | set(KEYWORDS) | set(REPLACEMENTS) | set(DESCRIPTIONS) | set(FIELD_REPLACEMENTS)
    | {("lumimathpro", locale) for locale in MATH_LANGUAGE_NAMES}
)
TARGET_FIELDS = {
    cell: frozenset(
        ({"description", "promotionalText", "keywords"} if cell[0] == "aim990" else set())
        | ({"keywords"} if cell[0] == "lumibopomofo" or cell in KEYWORDS else set())
        | ({"description"} if cell in REPLACEMENTS or cell in DESCRIPTIONS or
           cell[0] == "lumimathpro" and cell[1] in MATH_LANGUAGE_NAMES else set())
        | set(FIELD_REPLACEMENTS.get(cell, {}))
    )
    for cell in TARGET_CELLS
}


def reviewed_values(key, locale, source, *, app_id, purchase_model):
    values = dict(source)
    cell = key, locale
    if cell not in TARGET_CELLS:
        return values
    if (str(app_id), purchase_model) != APP_FACTS[key]:
        raise ValueError(f"Indic App identity/purchase model drift: {key}/{locale}")
    if key == "aim990":
        values.update(AIM_COPY[locale])
    if key == "lumibopomofo":
        values["keywords"] = BOPOMOFO_KEYWORDS[locale]
    if cell in KEYWORDS:
        values["keywords"] = KEYWORDS[cell]
    if cell in DESCRIPTIONS:
        values["description"] = DESCRIPTIONS[cell]
    for field, replacements in FIELD_REPLACEMENTS.get(cell, {}).items():
        for old, new in replacements:
            if old in values[field]:
                values[field] = values[field].replace(old, new)
            elif new not in values[field]:
                raise ValueError(f"Indic reviewed field changed: {key}/{locale}/{field}")
    description = values["description"]
    for old, new in REPLACEMENTS.get(cell, ()):
        if old in description:
            description = description.replace(old, new)
        elif new not in description:
            raise ValueError(f"Indic reviewed source changed: {key}/{locale}: {old}")
    if key == "lumimathpro" and locale in MATH_LANGUAGE_NAMES:
        english, chinese, japanese, korean = MATH_LANGUAGE_NAMES[locale]
        for old, new in (("English ·", english + " ·"), ("繁體中文", chinese), ("日本語", japanese), ("한국어", korean)):
            description = description.replace(old, new)
    if description != source["description"] and DISCLOSURES[locale] not in description:
        description += "\n\n" + DISCLOSURES[locale]
    values["description"] = description
    for field in FIELDS:
        if not isinstance(values.get(field), str) or not values[field].strip():
            raise ValueError(f"Empty Indic reviewed field: {key}/{locale}/{field}")
    return values
