def external_values(key, locale, values):
    if locale != "pt-PT":
        return values
    result = {**values, **EXTERNAL_OVERRIDES.get(key, {})}
    for field, revisions in EXTERNAL_REVISIONS.get(key, {}).items():
        value = result.get(field)
        if isinstance(value, str):
            for original, reviewed in revisions:
                value = value.replace(original, reviewed)
            result[field] = value
    return result
